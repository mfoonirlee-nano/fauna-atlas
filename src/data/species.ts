const taxon = (scientificName: string, zhName: string): Taxon => ({
  scientificName,
  zhName,
});

const animalTaxonomy = (
  phylum: Taxon,
  className: Taxon,
  order: Taxon,
  family: Taxon,
  genus: Taxon,
): SpeciesTaxonomy => ({
  kingdom: taxon('Animalia', '动物界'),
  phylum,
  class: className,
  order,
  family,
  genus,
});

const conservation = (
  code: IucnStatusCode,
  trend: PopulationTrend,
  assessedYear: number,
  criteria?: string,
): ConservationStatus => ({
  system: 'IUCN Red List',
  code,
  label: iucnLabels[code],
  trend,
  assessedYear,
  criteria,
  assessor: 'International Union for Conservation of Nature (IUCN)',
});

